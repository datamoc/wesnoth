/**
 * Compile Wesnoth's gettext catalogs into the generated data.
 *
 * The real game loads a `.po` (or `.mo`) per language at startup
 * (`src/language.cpp`); the port compiles a curated set into one module, because
 * the offline build is a single file that cannot fetch a catalog at run time.
 * The set covers the languages mainline content is most translated into, plus
 * Arabic so the right-to-left path (`isRtlLanguage`, alignment) is a real case
 * rather than a hypothetical one.
 *
 * `npm run data` runs this; the catalogs are read from `po/wesnoth/<locale>.po`
 * in the checkout.
 */
import fs from 'node:fs';
import path from 'node:path';
import { parsePo, pluralFormsOf } from '../src/ui/i18n.ts';

const root = path.resolve(import.meta.dirname, '..');
const poDir = path.resolve(root, '..', 'po', 'wesnoth');

/** The shipped languages, with the endonym the preferences screen lists. */
export const LOCALES: readonly { id: string; name: string }[] = [
  { id: 'de', name: 'Deutsch' },
  { id: 'es', name: 'Español' },
  { id: 'fr', name: 'Français' },
  { id: 'it', name: 'Italiano' },
  { id: 'ja', name: '日本語' },
  { id: 'pl', name: 'Polski' },
  { id: 'ru', name: 'Русский' },
  { id: 'zh_CN', name: '中文（简体）' },
  { id: 'ar', name: 'العربية' },
];

const catalogs: Record<string, { entries: Record<string, readonly string[]>; pluralForms: number }> = {};
for (const locale of LOCALES) {
  const file = path.join(poDir, `${locale.id}.po`);
  if (!fs.existsSync(file)) throw new Error(`missing catalog: ${file}`);
  const catalog = parsePo(fs.readFileSync(file, 'utf8'), locale.id);
  catalogs[locale.id] = {
    entries: Object.fromEntries([...catalog.entries].map(([id, entry]) => [id, entry.translations])),
    pluralForms: pluralFormsOf(catalog),
  };
}

const output = path.join(root, 'src', 'generated', 'i18n.ts');
const header = `// Generated by tools/compile-i18n.ts - do not edit.
// Wesnoth's real gettext catalogs, one entry map per language.
export interface GeneratedCatalog {
  readonly entries: Readonly<Record<string, readonly string[]>>;
  /** how many plural slots the catalog's Plural-Forms header declares */
  readonly pluralForms: number;
}
export const LOCALE_NAMES: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries(LOCALES.map((locale) => [locale.id, locale.name])), null, '\t')} as const;
export const CATALOGS: Readonly<Record<string, GeneratedCatalog>> = `;
fs.writeFileSync(output, `${header}${JSON.stringify(catalogs, null, '\t')} as const;\n`, 'utf8');
const total = Object.values(catalogs).reduce((sum, catalog) => sum + Object.keys(catalog.entries).length, 0);
console.log(`i18n: ${LOCALES.length} catalog(s), ${total} entries -> ${path.relative(root, output)}`);
