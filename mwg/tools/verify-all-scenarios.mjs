/**
 * Loads every compiled scenario in one headless Chrome session of the built
 * `dist/index.html`, plays a few turns of each through the scene's own turn loop
 * (human side ended, AI sides moved, dialogues advanced), and reports every scenario
 * that throws, logs a page error, renders an empty map or has no units. Also checks
 * that every campaign's scenario chain resolves in the registry.
 *
 *   node tools/verify-all-scenarios.mjs [--turns 3] [--only prefix] [--campaigns]
 */
import { execFileSync, spawn } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { usableProfileDir } from './chrome-profile.mjs';

const mwgDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const distEntry = path.join(mwgDir, process.env.VERIFY_DIST ?? 'dist', 'index.html');
const PORT = Number(process.env.VERIFY_PORT ?? 9335);
const wantedProfileDir = path.join(mwgDir, PORT === 9335 ? '.verify-chrome-profile-all' : `.verify-chrome-profile-all-${PORT}`);

function findChrome() {
  const candidates = [
    process.env.CHROME_PATH,
    'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',
    'C:\\Program Files (x86)\\Google\\Chrome\\Application\\chrome.exe',
    'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe',
    'C:\\Program Files\\Microsoft\\Edge\\Application\\msedge.exe',
    '/usr/bin/google-chrome',
    '/usr/bin/chromium',
    '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  ].filter(Boolean);
  return candidates.find((candidate) => fs.existsSync(candidate)) ?? null;
}

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function devtoolsTarget() {
  for (let attempt = 0; attempt < 60; attempt++) {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 400);
    try {
      const response = await fetch(`http://127.0.0.1:${PORT}/json/list`, { signal: controller.signal });
      const list = await response.json();
      const page = list.find((entry) => entry.type === 'page' && entry.webSocketDebuggerUrl);
      if (page) return page;
    } catch {
      // endpoint not up yet
    } finally {
      clearTimeout(timeout);
    }
    await sleep(500);
  }
  throw new Error('Chrome DevTools endpoint never came up');
}

class Cdp {
  constructor(ws) {
    this.ws = ws;
    this.nextId = 1;
    this.pending = new Map();
    this.events = [];
    ws.addEventListener('message', (event) => {
      const message = JSON.parse(event.data);
      if (message.id && this.pending.has(message.id)) {
        const { resolve, reject } = this.pending.get(message.id);
        this.pending.delete(message.id);
        if (message.error) reject(new Error(JSON.stringify(message.error)));
        else resolve(message.result);
      } else if (message.method) {
        this.events.push(message);
      }
    });
  }

  send(method, params = {}) {
    const id = this.nextId++;
    return new Promise((resolve, reject) => {
      this.pending.set(id, { resolve, reject });
      this.ws.send(JSON.stringify({ id, method, params }));
    });
  }
}


const argv = process.argv.slice(2);
const turns = argv.includes('--turns') ? Number(argv[argv.indexOf('--turns') + 1]) : 3;
const bot = argv.includes('--bot');
const limitMs = argv.includes('--timeout') ? Number(argv[argv.indexOf('--timeout') + 1]) * 1000 : 120000;
const outcomes = {};
const only = argv.includes('--only') ? argv[argv.indexOf('--only') + 1] : '';

const { SCENARIO_ORDER, MULTIPLAYER_SCENARIO_ORDER, SCENARIOS } = await import('../src/generated/scenarios.ts');
const { CAMPAIGNS } = await import('../src/generated/campaigns.ts');
const names = [...SCENARIO_ORDER, ...MULTIPLAYER_SCENARIO_ORDER].filter((name) => name.startsWith(only));
const wcMode = argv.includes('--wc');

const chain = [];
for (const campaign of CAMPAIGNS) {
  if (campaign.firstScenario === 'wc-lua') continue; // generated by Lua, nothing to look up
  for (const id of campaign.scenarios) if (!SCENARIOS[id]) chain.push(`${campaign.id}: ${id} missing from the registry`);
}

// A browser left behind by an earlier run can still hold this profile; clearing
// it is what decides whether the gate starts at all, so it is not a bare rmSync.
const profileDir = usableProfileDir(wantedProfileDir);
const chrome = spawn(findChrome(), [
  '--headless=new', '--js-flags=--expose-gc', '--no-sandbox', '--disable-gpu', '--disable-software-rasterizer', '--no-first-run',
  `--remote-debugging-port=${PORT}`, `--user-data-dir=${profileDir}`, '--window-size=1400,900',
  `file:///${distEntry.split(path.sep).join('/')}#freelands`,
], { stdio: 'ignore' });

const failures = [...chain];
let played = 0;
try {
  const target = await devtoolsTarget();
  const ws = new WebSocket(target.webSocketDebuggerUrl);
  await new Promise((resolve, reject) => { ws.addEventListener('open', resolve); ws.addEventListener('error', reject); });
  const cdp = new Cdp(ws);
  await cdp.send('Runtime.enable');
  await cdp.send('Log.enable');
  const evaluate = async (expression, timeout = 120000) => {
    const result = await Promise.race([
      cdp.send('Runtime.evaluate', { expression, returnByValue: true, awaitPromise: true }),
      new Promise((_, reject) => setTimeout(() => reject(new Error('timeout')), timeout)),
    ]);
    if (result.exceptionDetails) throw new Error(result.exceptionDetails.exception?.description ?? result.exceptionDetails.text);
    return result.result.value;
  };
  for (let attempt = 0; attempt < 60 && !(await evaluate('!!(window.__WESNOTH__ && window.__WESNOTH__.state)')); attempt++) await sleep(1000);
  const errorsSince = (from) => cdp.events.slice(from)
    .filter((event) => event.method === 'Runtime.exceptionThrown' || (event.method === 'Runtime.consoleAPICalled' && event.params.type === 'error') || (event.method === 'Log.entryAdded' && event.params.entry.level === 'error'))
    .map((event) => event.method === 'Runtime.exceptionThrown' ? (event.params.exceptionDetails?.exception?.description ?? event.params.exceptionDetails?.text) : event.method === 'Runtime.consoleAPICalled' ? event.params.args.map((arg) => arg.value ?? arg.description ?? '').join(' ') : event.params.entry.text);
  if (argv.includes('--chain')) {
    // Every campaign from its first scenario: force the win at once (so no unit is lost to a passive player), and follow the
    // carry-over into the next scenario until the campaign's own chain ends.
    for (const campaign of CAMPAIGNS) {
      if (campaign.firstScenario === 'wc-lua') continue;
      const from = cdp.events.length;
      try {
        const report = await evaluate(`(async () => {
          const s = window.__WESNOTH__.scene;
          const campaign = window.__WESNOTH__.campaigns.find((c) => c.id === ${JSON.stringify(campaign.id)});
          s.startCampaign(campaign, campaign.defaultDifficulty || 'NORMAL');
          const visited = [];
          for (let step = 0; step < 60; step++) {
            for (let i = 0; i < 3; i++) s.update(0.016);
            let guard = 0;
            while (s.dialogueOpen && guard++ < 200) s.advanceDialogue();
            visited.push(s.scenarioName + ':' + s.state.units.length);
            // a talk-only scenario (an epilogue on NO_MAP_DATA) legitimately has no unit on its map
            s.outcome = 'won';
            s.finishScenario();
            const carryover = s.carryover;
            s.__lastCarry = carryover ? { to: carryover.to, units: carryover.units.length, gold: carryover.gold } : null;
            if (!carryover) break;
            s.startScenario(carryover.to, carryover);
          }
          return visited;
        })()`, limitMs);
        console.log(`  chain ${campaign.id}: ${report.length} scenarios`);
        if (report.length < Math.min(campaign.scenarios.length, 2)) failures.push(`chain ${campaign.id}: only ${report.length} scenario(s) reached of ${campaign.scenarios.length}`);
      } catch (error) {
        failures.push(`chain ${campaign.id}: ${String(error.message).slice(0, 200)}`);
      }
      for (const message of errorsSince(from)) failures.push(`chain ${campaign.id}: ${message}`);
    }
    names.length = 0;
  }
  if (argv.includes('--trace01')) {
    const trace = await evaluate(`(async () => {
      const s = window.__WESNOTH__.scene;
      const campaign = window.__WESNOTH__.campaigns.find((c) => c.id === 'Heir 2 The Throne');
      const snap = (tag) => ({ tag, units: s.state.units.filter((u) => u.side === 1).map((u) => u.typeId + ':' + u.name + ':' + u.id + '@' + u.x + ',' + u.y), byId: [...s.unitsById.keys()].filter((k) => s.unitsById.get(k).side === 1), stored: [...s.storedUnits.keys()], dlg: s.dialogueOpen, round: s.state.round });
      const out = [];
      const origDelete = Map.prototype.delete; const origSet = Map.prototype.set;
      Map.prototype.delete = function (k) { if (k === 'Konrad') out.push({ del: String(new Error().stack).split(String.fromCharCode(10)).slice(2, 6).map((l) => l.trim().slice(0, 90)) }); return origDelete.call(this, k); };
      Map.prototype.set = function (k, v) { if (k === 'Konrad') out.push({ set: v && v.typeId, stack: String(new Error().stack).split(String.fromCharCode(10)).slice(2, 4).map((l) => l.trim().slice(0, 90)) }); return origSet.call(this, k, v); };
      s.startCampaign(campaign, 'NORMAL');
      Map.prototype.delete = origDelete; Map.prototype.set = origSet;
      out.push(snap('after start'));
      out.push({ allById: [...s.unitsById.entries()].filter(([k]) => /onrad|redmage|14/.test(k)).map(([k, u]) => k + '=' + u.typeId + '/' + u.side + '/' + u.id), konradInState: s.state.units.filter((u) => /onrad|Fighter/.test(u.typeId + u.name)).map((u) => u.typeId + '/' + u.side + '/' + u.id + '/' + u.wmlId) });
      out.push({ types: ['Fighter','Unarmed_Fighter','Sleeping_Fighter'].map((t) => t + ':' + !!window.__WESNOTH__.data.unitTypes[t]), world: Object.entries(s.runtime.world.units).filter(([, u]) => u.side === 1 || u.side === '1').map(([k, u]) => k + ':' + u.type + '@' + u.x + ',' + u.y + ':' + u.alive) });
      for (let i = 0; i < 6; i++) { for (let k = 0; k < 20; k++) { if (s.dialogueOpen) s.advanceDialogue(); s.update(0.25); } out.push(snap('step' + i)); }
      return out;
    })()`, limitMs);
    for (const row of trace) console.log('  trace', JSON.stringify(row));
    names.length = 0;
  }
  if (argv.includes('--memprobe')) {
    // Heap after a forced GC following each scenario start: a flat line is no leak, a staircase is.
    const count = argv.includes('--count') ? Number(argv[argv.indexOf('--count') + 1]) : 40;
    const sample = async () => {
      await cdp.send('HeapProfiler.collectGarbage');
      const heap = await cdp.send('Runtime.getHeapUsage');
      const dom = await cdp.send('Memory.getDOMCounters');
      // native memory (textures, canvas, decoded images) is outside the JS heap: sum this run's Chrome processes
      const script = `(Get-CimInstance Win32_Process -Filter "Name='chrome.exe'" | Where-Object { $_.CommandLine -like '*${path.basename(profileDir)}*' } | ForEach-Object { (Get-Process -Id $_.ProcessId -ErrorAction SilentlyContinue).WorkingSet64 } | Measure-Object -Sum).Sum`;
      const chromeMB = Math.round(Number(execFileSync('powershell', ['-NoProfile', '-Command', script], { encoding: 'utf8' }).trim() || 0) / 1048576);
      return { heapMB: Math.round(heap.usedSize / 1048576), chromeMB, nodes: dom.nodes, listeners: dom.jsEventListeners };
    };
    await cdp.send('Memory.getDOMCounters').catch(() => {});
    const rows = [];
    for (let i = 0; i < Math.min(count, names.length); i++) {
      await evaluate(`(async () => { const s = window.__WESNOTH__.scene; s.startScenario(${JSON.stringify(names[i])}); for (let k = 0; k < 3; k++) s.update(0.016); return true; })()`, limitMs);
      const row = { n: i + 1, scenario: names[i], ...(await sample()) };
      rows.push(row);
      if (i % 20 === 19 || i === 0) console.log('  mem', JSON.stringify(row));
    }
    console.log('  mem-summary', JSON.stringify({ first: rows[0]?.heapMB, last: rows[rows.length - 1]?.heapMB, max: Math.max(...rows.map((r) => r.heapMB)) }));
    names.length = 0;
  }
  if (argv.includes('--overworld')) {
    // HttT: win 01, reach the overworld (00), step Konrad onto the POI of scenario s02 and check the
    // scenario card is answered and the level ends towards that scenario.
    const from = cdp.events.length;
    try {
      const report = await evaluate(`(async () => {
        const s = window.__WESNOTH__.scene;
        const campaign = window.__WESNOTH__.campaigns.find((c) => c.id === 'Heir 2 The Throne');
        s.startCampaign(campaign, 'NORMAL');
        const frames = () => { for (let i = 0; i < 3; i++) s.update(0.016); };
        const drain = () => { let g = 0; frames(); while (g++ < 400) { if (s.dialogueOpen) s.advanceDialogue(); s.update(0.25); } };
        drain();
        const dbg = { s01units: s.state.units.filter((u) => u.side === 1).map((u) => u.id + '@' + u.x + ',' + u.y), byId: [...s.unitsById.entries()].filter(([, u]) => u.side === 1).map(([k, u]) => k + ':' + u.typeId + ':' + u.hitpoints), stateUnits: s.state.units.filter((u) => u.side === 1).map((u) => u.typeId + ':' + u.name + ':' + u.hitpoints), stored: [...s.storedUnits.keys()], recall: s.recallList.map((u) => u.typeId + ':' + u.name), world: Object.entries(s.runtime.world.units).filter(([, u]) => u.side === 1 || /onrad/.test(u.id || '')).map(([k, u]) => k + ':' + u.type + '@' + u.x + ',' + u.y + (u.alive ? '' : ':dead')), dialogueOpen: s.dialogueOpen, round: s.state.round, turn: s.state.turn, sideTurn: s.state.sides && s.state.sides[s.state.currentSide ?? 0], msgs: (s.runtime.messages || s.runtime.world.messages || []).length, title: s.scenarioName, log: String(s.log).slice(0, 100) };
        s.outcome = 'won'; s.finishScenario();
        dbg.carry = s.carryover && { to: s.carryover.to, units: s.carryover.units.map((u) => u.id || u.name) };
        if (!s.carryover) return { error: 'no carryover from 01' };
        s.startScenario(s.carryover.to, s.carryover);
        drain();
        const konrad = s.state.units.find((u) => u.side === 1 && /konrad|fighter/i.test(u.name + u.typeId)) ?? s.state.units.find((u) => u.side === 1);
        if (!konrad) return { dbg, error: 'no Konrad in ' + s.scenarioName, units: s.state.units.filter((u) => u.side === 1).map((u) => u.id) };
        const from = { x: konrad.x, y: konrad.y };
        const vars = s.runtime.world.variables;
        const out = { scenario: s.scenarioName, from, tried: [] };
        for (const [x, y] of [[15, 53], [16, 54]]) {
          konrad.x = x; konrad.y = y;
          s.reportMove(konrad, null, from);
          drain();
          out.tried.push({ x, y, status: vars.status_s02 ?? null, next: vars.__next_scenario ?? null, outcome: s.outcome, log: String(s.log).slice(0, 120) });
          if (vars.__next_scenario || s.outcome !== 'playing') break;
          konrad.x = from.x; konrad.y = from.y;
        }
        return out;
      })()`, limitMs);
      console.log('  overworld', JSON.stringify(report));
      const last = report.tried?.[report.tried.length - 1];
      if (report.error || !last || (!last.next && last.outcome === 'playing')) failures.push(`overworld: no exit (${JSON.stringify(report).slice(0, 300)})`);
    } catch (error) {
      failures.push(`overworld: ${String(error.message).slice(0, 300)}`);
    }
    for (const message of errorsSince(from)) failures.push(`overworld: ${message}`);
    names.length = 0;
  }
  if (wcMode) {
    // World Conquest through its real Lua: generate, start and play maps one after another.
    const wcResults = [];
    const faction = argv.includes('--faction') ? argv[argv.indexOf('--faction') + 1] : 'The Trust';
    const from = cdp.events.length;
    try {
      await evaluate(`(async () => { const s = window.__WESNOTH__.scene; s.startWorldConquest(${JSON.stringify(faction)}, 'NORMAL'); for (let i = 0; i < 4; i++) s.update(0.016); return true; })()`, limitMs);
      const maxMaps = argv.includes('--maps') ? Number(argv[argv.indexOf('--maps') + 1]) : 2;
      for (let map = 1; map <= maxMaps; map++) {
        const report = await evaluate(`(async () => {
          const s = window.__WESNOTH__.scene;
          const frames = () => { for (let i = 0; i < 3; i++) s.update(0.016); };
          frames();
          const start = { units: s.state.units.length, w: s.state.width, h: s.state.height, title: s.scenarioTitle(), gold: s.gold[1] };
          for (let t = 0; t < ${turns}; t++) {
            let guard = 0;
            while ((s.dialogueOpen || s.luaDialog) && guard++ < 200) { if (!s.autoAnswerLuaDialog()) s.advanceDialogue(); }
            if (s.outcome !== 'playing') break;
            // --cheat-win: wipe the enemy on turn 3 so the next map can be reached without a human
            if (${argv.includes('--cheat-win')} && t === 1) { s.state.units = s.state.units.filter((u) => u.side === 1); s.evaluateOutcome(); frames(); break; }
            if (${bot}) s.aiTurn(s.state.sides[0]);
            s.finishTurn();
            frames();
          }
          return { ...start, turn: s.state.turn, log: String(s.log).slice(0, 160), outcome: s.outcome, round: s.state.round, unitsEnd: s.state.units.length, luaError: String(s.log).startsWith('Lua:') ? s.log : null };
        })()`, limitMs);
        wcResults.push(report);
        console.log('  WC map', map, JSON.stringify(report));
        if (report.outcome === 'won' && map < maxMaps) await evaluate('(async () => { window.__WESNOTH__.scene.continueWorldConquest(); return true; })()', limitMs);
        else break;
      }
    } catch (error) {
      failures.push(`world-conquest: ${String(error.message).slice(0, 300)}`);
    }
    for (const message of errorsSince(from)) failures.push(`world-conquest: ${message}`);
    for (const result of wcResults) if (result.luaError) failures.push(`world-conquest: ${result.luaError}`);
    names.length = 0;
  }
  for (const name of names) {
    const from = cdp.events.length;
    let report;
    try {
      report = await evaluate(`(async () => {
        const s = window.__WESNOTH__.scene;
        s.campaign = null;
        s.enterScenario(${JSON.stringify(name)}, null);
        const frames = () => { for (let i = 0; i < 3; i++) s.update(0.016); };
        frames();
        const first = { w: s.state.width, h: s.state.height, units: s.state.units.length, terrain: s.terrainLayer.children.length + s.terrainForegroundLayer.children.length };
        let played = 0;
        for (let t = 0; t < ${turns}; t++) {
          let guard = 0;
          while (s.dialogueOpen && guard++ < 200) s.advanceDialogue();
          if (s.outcome !== 'playing') break;
          // --bot: the human side is played by the AI planner too, so a scenario can run to
          // its own victory, defeat or turn limit without a person.
          if (${bot}) s.aiTurn(s.state.sides[0]);
          s.finishTurn();
          frames();
          played++;
        }
        return { ...first, played, outcome: s.outcome, round: s.state.round, unitsEnd: s.state.units.length };
      })()`, limitMs);
    } catch (error) {
      failures.push(`${name}: ${String(error.message).slice(0, 200)}`);
      continue;
    }
    outcomes[report.outcome] = (outcomes[report.outcome] ?? 0) + 1;
    if (report.outcome === 'playing') console.log(`  still playing: ${name} (round ${report.round}, ${report.played} bot turns, ${report.unitsEnd} units)`);
    const errors = errorsSince(from);
    const problems = [];
    if (report.w < 1 || report.h < 1) problems.push('empty map');
    if (report.terrain === 0) problems.push('no terrain drawn');
    if (errors.length) problems.push(`page errors: ${errors.slice(0, 2).join(' | ')}`);
    if (problems.length) failures.push(`${name}: ${problems.join('; ')}`);
    played++;
    if (played % 25 === 0) console.log(`  ${played}/${names.length} scenarios loaded and played`);
  }
} finally {
  chrome.kill();
}
console.log(JSON.stringify({ ok: failures.length === 0, scenarios: names.length, turnsPerScenario: turns, bot, outcomes, failures }, null, 2));
process.exit(failures.length ? 1 : 0);
