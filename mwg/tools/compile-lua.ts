/**
 * Bundle the Lua the Wesnoth kernel loads, and World Conquest's WML data, into the generated
 * data (the offline build is one file and cannot fetch scripts at run time).
 *
 * - `src/generated/lua-files.ts`: every `.lua` under `data/lua` (the engine's own core
 *   library), `data/ai` (the micro-AI helpers `lua/wml` requires) and
 *   `data/campaigns/World_Conquest/lua`, keyed by path relative to `data/`.
 * - `src/generated/wc-data.ts`: World Conquest's `[era]`, `[resource]`s and `[campaign]`
 *   definitions as JSON Lua-config tables (`src/scripting/wml-bridge.ts`).
 *
 * `npm run data` runs this.
 */
import fs from 'node:fs';
import path from 'node:path';
import { WmlPreprocessor, parseWml } from '../src/simulation/wml.ts';
import { wmlContents } from '../src/scripting/wml-bridge.ts';

const root = path.resolve(import.meta.dirname, '..');
const dataDir = path.resolve(root, '..', 'data');
const generatedDir = path.join(root, 'src', 'generated');

// World Conquest's `gui/*.cfg` are the dialog definitions its Lua loads with `wml.load`.
const SOURCES = ['lua', 'ai', path.join('campaigns', 'World_Conquest', 'lua'), path.join('campaigns', 'World_Conquest', 'gui')];

function walk(dir: string, out: string[] = []): string[] {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (entry.name.endsWith('.lua') || (entry.name.endsWith('.cfg') && full.includes(`${path.sep}gui${path.sep}`))) out.push(full);
  }
  return out;
}

const files: Record<string, string> = {};
for (const source of SOURCES) {
  const base = path.join(dataDir, source);
  if (!fs.existsSync(base)) continue;
  for (const file of walk(base)) {
    files[path.relative(dataDir, file).split(path.sep).join('/')] = fs.readFileSync(file, 'utf8');
  }
}
fs.mkdirSync(generatedDir, { recursive: true });
fs.writeFileSync(
  path.join(generatedDir, 'lua-files.ts'),
  `// Generated by tools/compile-lua.ts - do not edit.\nexport const LUA_FILES: Record<string, string> = ${JSON.stringify(files)};\n`,
  'utf8',
);

// World Conquest's WML: the era, its resources and its campaign definitions.
const preprocessor = new WmlPreprocessor({ dataDir, defines: ['LOAD_WC2', 'MULTIPLAYER'], onFile: () => {} });
const macros = path.join(dataDir, 'core', 'macros');
preprocessor.loadMacros(fs.readdirSync(macros).filter((name) => name.endsWith('.cfg')).map((name) => path.join(macros, name)));
const main = path.join(dataDir, 'campaigns', 'World_Conquest', '_main.cfg');
const nodes = parseWml(preprocessor.preprocessFile(main), main);
const era = nodes.find((node) => node.tag === 'era');
const resources = nodes.filter((node) => node.tag === 'resource').map((node) => wmlContents(node));
const campaigns = nodes.filter((node) => node.tag === 'campaign').map((node) => wmlContents(node));
fs.writeFileSync(
  path.join(generatedDir, 'wc-data.ts'),
  `// Generated by tools/compile-lua.ts - do not edit.\nexport const WC_ERA = ${JSON.stringify(era ? wmlContents(era) : {})} as Record<string, unknown>;\nexport const WC_RESOURCES = ${JSON.stringify(resources)} as Record<string, unknown>[];\nexport const WC_CAMPAIGNS = ${JSON.stringify(campaigns)} as Record<string, unknown>[];\n`,
  'utf8',
);
const bytes = Object.values(files).reduce((sum, text) => sum + text.length, 0);
console.log(`compile-lua: ${Object.keys(files).length} Lua files (${Math.round(bytes / 1024)} KB), World Conquest era with ${era?.children.length ?? 0} children, ${resources.length} resources, ${campaigns.length} campaign definitions -> src/generated`);
