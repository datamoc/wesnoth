import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dist = join(here, '..', 'dist');
const gameIcon = join(here, '..', '..', 'data', 'core', 'images', 'wesnoth-icon.png');

//vite marks its entry script type="module" crossorigin no matter what format it emitted.
//That attribute makes a file:// page refuse to run it (ES modules are blocked by CORS from
//the file: origin), even though the bundle itself is a plain IIFE - so rewrite the tag.
const html = await readFile(join(dist, 'index.html'), 'utf8');
const entryTag = /[ \t]*<script[^>]*src="\.\/game\.js"[^>]*><\/script>/;

if (!entryTag.test(html)) {
	throw new Error('could not find the game script tag in vite output, check vite.config.ts');
}

/**
 * Packaging (ROADMAP P10): the same page is a `file://` build and an installable
 * web app. The manifest and the service worker are emitted beside it, and the
 * registration is injected here rather than in `index.html`, so the source page
 * stays a plain dev page. A service worker cannot run from `file://`, where the
 * page is already local.
 */
const iconName = 'wesnoth-icon.png';
await mkdir(join(dist, 'icons'), { recursive: true });
await copyFile(gameIcon, join(dist, 'icons', iconName));

const manifest = {
	name: 'Battle for Wesnoth',
	short_name: 'Wesnoth',
	description: 'Battle for Wesnoth (GPL-2.0-or-later), ported to TypeScript on the mwg framework.',
	start_url: './index.html',
	scope: './',
	display: 'fullscreen',
	orientation: 'any',
	background_color: '#08080c',
	theme_color: '#08080c',
	icons: [
		{ src: `./icons/${iconName}`, sizes: '128x128', type: 'image/png', purpose: 'any' },
	],
};
await writeFile(join(dist, 'manifest.webmanifest'), `${JSON.stringify(manifest, null, '\t')}\n`, 'utf8');

// Cache-first: the built page is one big file plus a handful of icons, so a
// second visit is served from the cache and works with no network at all.
const serviceWorker = `/* Generated by tools/emit.mjs - the offline shell for the hosted build. */
const CACHE = 'mwg-wesnoth-v1';
const SHELL = ['./index.html', './game.js', './manifest.webmanifest', './icons/wesnoth-icon.png'];
self.addEventListener('install', (event) => {
	event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(SHELL)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (event) => {
	event.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (event) => {
	if (event.request.method !== 'GET') return;
	event.respondWith(caches.match(event.request).then((hit) => hit || fetch(event.request)));
});
`;
await writeFile(join(dist, 'sw.js'), serviceWorker, 'utf8');

// The icon links are safe from anywhere; the manifest link is injected at run
// time below, because a `file://` page cannot fetch it (the browser refuses the
// cross-origin request and logs a CORS error), and the offline build has no
// manifest to give it.
const head = `	<link rel="apple-touch-icon" href="./icons/${iconName}">
	<link rel="icon" href="./icons/${iconName}">`;
const register = `<script>
		// The manifest and the service worker are the hosted build's: a file://
		// page cannot fetch a manifest (CORS) and needs no cache.
		if (location.protocol === 'http:' || location.protocol === 'https:') {
			var link = document.createElement('link');
			link.rel = 'manifest';
			link.href = './manifest.webmanifest';
			document.head.appendChild(link);
			addEventListener('load', function () { navigator.serviceWorker.register('./sw.js').catch(function () {}); });
		}
	</script>`;

let output = html.replace(entryTag, '\t<script defer src="./game.js"></script>');
output = output.replace('\t<title>', `\t${head}\n\t<title>`);
output = output.replace('</body>', `\t${register}\n</body>`);
await writeFile(join(dist, 'index.html'), output, 'utf8');
console.log('dist/index.html rewritten for file://, with a manifest, an icon and a service worker for the hosted build');
